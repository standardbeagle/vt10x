package vt10x

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/ioutil"
	"testing"

	"github.com/rivo/uniseg"
)

var updateWidthTable = flag.Bool("update-width-table", false, "rewrite width_table.go from uniseg")

// plainPrefixes are clusters that end in each kind of character that could
// pull a following character into itself: a base, a base with a mark, an emoji
// ZWJ join, a regional indicator, and every Hangul jamo class.
var plainPrefixes = []string{
	"a", "é", "\U0001F469‍", "\U0001F1EF", "ᄀ", "ᅡ", "ᆨ", "가", "각",
}

// referenceFastWidth is the definition of fastWidth: r is a standalone
// character of width 1 or 2 that starts a new cluster after any prefix in
// plainPrefixes and never begins one that swallows a following "a" (Prepend).
// It returns 0 otherwise.
func referenceFastWidth(r rune) uint8 {
	if r >= 0xD800 && r <= 0xDFFF {
		return 0
	}
	s := string(r)
	cluster, _, w, _ := uniseg.FirstGraphemeClusterInString(s, -1)
	if cluster != s || (w != 1 && w != 2) {
		return 0
	}
	if c, _, _, _ := uniseg.FirstGraphemeClusterInString(s+"a", -1); c != s {
		return 0 // Prepend
	}
	for _, p := range plainPrefixes {
		if c, _, _, _ := uniseg.FirstGraphemeClusterInString(p+s, -1); c != p {
			return 0
		}
	}
	return uint8(w)
}

func buildWidthTable() []byte {
	var pages [][256]uint8
	index := [256]uint8{}
	seen := map[[256]uint8]uint8{}
	for hi := 0; hi < 256; hi++ {
		var page [256]uint8
		for lo := 0; lo < 256; lo++ {
			page[lo] = referenceFastWidth(rune(hi<<8 | lo))
		}
		n, ok := seen[page]
		if !ok {
			n = uint8(len(pages))
			seen[page] = n
			pages = append(pages, page)
		}
		index[hi] = n
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `go test -run TestWidthTableIsCurrent -update-width-table`; DO NOT EDIT.\n\npackage vt10x\n\n")
	b.WriteString("// widthPageIndex maps the high byte of a BMP rune to a page in widthPages.\n")
	b.WriteString("var widthPageIndex = [256]uint8{")
	for i, v := range index {
		if i%32 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%d,", v)
	}
	b.WriteString("\n}\n\n// widthPages holds fastWidth's answer for each low byte, deduplicated.\nvar widthPages = [...][256]uint8{\n")
	for _, p := range pages {
		b.WriteString("\t{")
		for i, v := range p {
			if i%32 == 0 {
				b.WriteString("\n\t\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "%d,", v)
		}
		b.WriteString("\n\t},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

func TestWidthTableIsCurrent(t *testing.T) {
	want := buildWidthTable()
	if *updateWidthTable {
		if err := ioutil.WriteFile("width_table.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := ioutil.ReadFile("width_table.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("width_table.go is stale; run: go test -run TestWidthTableIsCurrent -update-width-table")
	}
}

func TestFastWidthAnswers(t *testing.T) {
	cases := map[rune]int{
		'a': 1, '~': 1, 'é': 1, '─': 1, '│': 1, '█': 1, '…': 1, '·': 1, '世': 2, '日': 2, 'ａ': 2, 'ア': 2, '한': 0, // precomposed Hangul LV can be joined by a jamo: segmenter
		'́': 0, '‍': 0, '️': 0, '​': 0, '؀': 0, // mark, ZWJ, VS16, ZWSP, Prepend
		'❤': 0, '✻': 1, '\U0001F600': 0, '\U0001F1EF': 0, // ExtPict, emoji, RI
		-1: 0, 0x110000: 0, '\U00020000': 0,
	}
	for r, want := range cases {
		if got := fastWidth(r); got != want {
			t.Errorf("fastWidth(%U) = %d, want %d", r, got, want)
		}
	}
	// A rune is only ever fast when the segmenter agrees, across the whole BMP.
	n := 0
	for r := rune(0); r < 0x10000; r++ {
		if got := fastWidth(r); got != int(referenceFastWidth(r)) {
			t.Fatalf("fastWidth(%U) = %d, reference %d", r, got, referenceFastWidth(r))
		} else if got != 0 {
			n++
		}
	}
	if n < 20000 {
		t.Errorf("only %d fast runes; the table has lost its coverage", n)
	}
}
